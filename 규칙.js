// 규칙.js - AI가 돌려준 판단 결과를 점검하고 다듬는다. (AI 대신 판단하지는 않는다)
//   - 빠진정보찾기: 날짜·장소·인원·작업내용 중 한 줄에 없어서 되물어야 할 것을 찾는다.
//   - 결과다듬기: 빈도·강도를 1~4 정수로 맞추고, 점수(빈도×강도)를 다시 계산하고, 8 이상이면 감소대책을 확인한다.
(function (전역) {
  "use strict";

  // 한 줄에 없어서 꼭 되물어야 하는 것(필수) / 있긴 하지만 맞는지 확인이 필요한 것(확인)
  function 빠진정보찾기(정보) {
    var 필수 = [], 확인 = [];
    if (!정보.날짜) 필수.push("날짜"); else if (정보.날짜확인필요) 확인.push("날짜");
    if (!정보.장소) 필수.push("장소");
    if (!정보.인원) 필수.push("인원");
    if (!정보.작업내용) 필수.push("작업내용");
    return { 필수: 필수, 확인: 확인 };
  }

  var 분류표 = { 추락: "03 추락", 전도: "03 추락", 감전: "02 전기", 낙하: "04 낙하·비래", 분진: "05 보건" };
  function 분류찾기(이름) {
    for (var k in 분류표) if (이름.indexOf(k) >= 0) return 분류표[k];
    return "09 기타";
  }

  // 근거: AI가 '작업내용' / '사진' / '둘다' 중 하나로 준다. 다른 말이 와도 셋 중 하나로 맞춘다.
  function 근거다듬기(글) {
    글 = String(글 || "").replace(/\s/g, "");
    if (/둘|모두|both/i.test(글)) return "둘다";
    if (/사진|이미지|photo|image/i.test(글)) return "사진";
    return "작업내용";
  }

  // 사진점검: [{ 번호, 본것, 상태(맞음/작업과다름/알아보기어려움), 설명 }]
  function 상태다듬기(글) {
    글 = String(글 || "").replace(/\s/g, "");
    if (/다름|관계없|무관|안맞|맞지않|mismatch/i.test(글)) return "작업과다름";
    if (/어려|흐림|어둡|알수없|불명|unclear|blur/i.test(글)) return "알아보기어려움";
    if (/맞음|일치|ok|match/i.test(글)) return "맞음";
    return "알아보기어려움";
  }
  function 사진점검다듬기(목록) {
    if (!Array.isArray(목록)) return [];
    return 목록.map(function (x, i) {
      x = x || {};
      return { 번호: Math.max(1, parseInt(x.번호, 10) || i + 1), 본것: String(x.본것 || ""), 상태: 상태다듬기(x.상태), 설명: String(x.설명 || "") };
    });
  }

  // 승인요청서: 혼재작업, 현장위험요인, 작업순서 3단계({단계, 조치}), 검토의견 (예전 사전조사·안전대책도 받는다)
  function 승인요청서다듬기(x) {
    x = x || {};
    var 순서 = (Array.isArray(x.작업순서) ? x.작업순서 : []).slice(0, 3).map(function (단) {
      단 = 단 || {};
      var 조치 = Array.isArray(단.조치) ? 단.조치.join("\n") : String(단.조치 || "");
      return { 단계: String(단.단계 || ""), 조치: 조치 };
    });
    return { 혼재작업: String(x.혼재작업 || ""), 현장위험요인: String(x.현장위험요인 || ""), 작업순서: 순서,
      검토의견: String(x.검토의견 || ""), 사전조사: String(x.사전조사 || ""), 안전대책: String(x.안전대책 || "") };
  }
  // 위험분류 번호: 1~6 정수. 없거나 이상하면 이름으로 짐작한다.
  var 분류번호표 = [[/추락|낙하|떨어|전도|넘어|중량|자세|요통/, 5], [/감전|전기|아크|누전/, 2], [/화재|폭발|가스|유해|화학|흄|중독/, 3], [/산소|질식|밀폐|온열|소음|조명|미끄/, 6], [/끼임|협착|베임|절단|부딪|충돌|공구|기계/, 1]];
  function 분류번호다듬기(번호, 이름) {
    var n = parseInt(번호, 10);
    if (n >= 1 && n <= 6) return n;
    var 글 = String(이름 || "");
    for (var i = 0; i < 분류번호표.length; i++) if (분류번호표[i][0].test(글)) return 분류번호표[i][1];
    return null;
  }

  // 빈도·강도는 1~4 정수여야 한다. 아니면 바꾸되, 바꿨다고 꼭 알려 준다.
  // 읽을 수 없는 값(예: "높음")은 안전하게 가장 높은 4로 넣는다 (위험을 낮게 잡지 않으려고).
  function 점수값(원래, 이름, 칸, 경고) {
    var 수 = Number(원래);
    if (원래 === null || 원래 === undefined || 원래 === "" || !isFinite(수)) {
      경고.push("'" + 이름 + "'의 " + 칸 + " 값(" + (원래 === undefined || 원래 === null || 원래 === "" ? "없음" : 원래) + ")을 읽을 수 없어서 가장 높은 4로 넣었어요. 꼭 확인해 주세요.");
      return 4;
    }
    var 바꾼 = Math.min(4, Math.max(1, Math.round(수)));
    if (바꾼 !== 수) 경고.push("'" + 이름 + "'의 " + 칸 + " 값(" + 원래 + ")이 1~4 정수가 아니라서 " + 바꾼 + "(으)로 바꿨어요. 확인해 주세요.");
    return 바꾼;
  }

  // AI가 준 결과가 조금 틀려도 서류에 넣을 수 있게 형식을 맞춘다.
  // 옵션: { 체크수: 고른 작업의 허가서 체크 항목 수, 공통수: 공통사항 항목 수 } (없으면 고소작업 8개, 공통 7개)
  function 결과다듬기(결과, 옵션) {
    옵션 = 옵션 || {};
    var 체크수 = 옵션.체크수 == null ? 8 : 옵션.체크수, 공통수 = 옵션.공통수 == null ? 7 : 옵션.공통수;
    var 경고 = [];
    var 정리 = {
      // 예전 이름(고소작업여부)으로 온 답도 받는다
      해당작업여부: 결과.해당작업여부 != null ? !!결과.해당작업여부 : !!결과.고소작업여부,
      범위밖사유: 결과.범위밖사유 || "",
      추천작업: String(결과.추천작업 || ""),
      정보: Object.assign({ 날짜: null, 날짜확인필요: false, 시간: null, 장소: null, 인원: null, 총인원: null,
        작업내용: "", 사용기구: [], 구분: "자체작업", 업체명: null }, 결과.정보 || {}),
      위험요인: [],
      허가서체크: { 공통: [], 작업: [] },
      승인요청서: 승인요청서다듬기(결과.승인요청서),
      허가서기타: (Array.isArray(결과.허가서기타) ? 결과.허가서기타 : []).map(function (x) { return String(typeof x === "object" && x ? (x.항목 || "") : (x || "")).trim(); }).filter(Boolean).slice(0, 2),
      허가서교육: [0, 1, 2, 3, 4].map(function (i) { return !!(결과.허가서교육 || [])[i]; }),
      TBM: Object.assign({ 위험요인: "", 안전대책: "", 교육내용: "" }, 결과.TBM || {}),
      안전중점: 결과.안전중점 || "",
      사진점검: 사진점검다듬기(결과.사진점검),
      경고: 경고,
    };
    if (!Array.isArray(정리.정보.사용기구)) 정리.정보.사용기구 = String(정리.정보.사용기구 || "").split(/\s*,\s*/).filter(Boolean);
    (결과.위험요인 || []).forEach(function (x) {
      var 이름 = String(x.위험요인 || "(이름 없음)");
      var 빈도 = 점수값(x.빈도, 이름, "빈도", 경고);
      var 강도 = 점수값(x.강도, 이름, "강도", 경고);
      var 점수 = 빈도 * 강도;
      var 항목 = { 위험요인: String(x.위험요인 || ""), 상황결과: String(x.상황결과 || ""), 현재조치: String(x.현재조치 || ""),
        분류: x.분류 || 분류찾기(String(x.위험요인 || "")), 빈도: 빈도, 강도: 강도, 점수: 점수,
        감소대책: "", 개선후빈도: null, 개선후강도: null, 개선후점수: null, 근거: 근거다듬기(x.근거), 분류번호: 분류번호다듬기(x.분류번호, (x.분류 || "") + " " + (x.위험요인 || "") + " " + (x.상황결과 || "")) };
      if (점수 >= 8) {
        항목.감소대책 = String(x.감소대책 || "");
        if (!항목.감소대책) 경고.push("'" + 항목.위험요인 + "'은 위험성 " + 점수 + "점이라 감소대책이 필요한데 비어 있습니다.");
        // 개선 후 빈도·강도는 AI가 준 값만 쓴다. 빠지면 지어내지 않고 비워 둔 뒤 알려 준다.
        var 후빈도 = Number(x.개선후빈도), 후강도 = Number(x.개선후강도);
        if (x.개선후빈도 == null || x.개선후강도 == null || !isFinite(후빈도) || !isFinite(후강도) || 후빈도 < 1 || 후빈도 > 4 || 후강도 < 1 || 후강도 > 4) {
          경고.push("'" + 항목.위험요인 + "'의 개선 후 빈도·강도를 AI가 주지 않았거나 1~4 밖이라 비워 두었어요. 직접 적어 주세요.");
        } else {
          항목.개선후빈도 = Math.round(후빈도);
          항목.개선후강도 = Math.round(후강도);
          항목.개선후점수 = 항목.개선후빈도 * 항목.개선후강도;
          if (항목.개선후점수 >= 8) 경고.push("'" + 항목.위험요인 + "'은 개선 후에도 위험성이 " + 항목.개선후점수 + "점(8 이상)이에요. 감소대책을 더 보강해 주세요.");
        }
      }
      정리.위험요인.push(항목);
    });
    if (정리.해당작업여부 && !정리.위험요인.length) 경고.push("AI가 위험요인을 하나도 찾지 못했어요. 위험성평가표가 비어 있으니 '다시 판단'을 누르거나 작업 내용을 더 자세히 적어 주세요.");
    var 체크 = 결과.허가서체크 || {};
    var 작업체크 = 체크.작업 || 체크.고소 || []; // 예전 이름(고소)으로 온 답도 받는다
    for (var i = 0; i < 공통수; i++) 정리.허가서체크.공통.push(!!(체크.공통 || [])[i]);
    for (var j = 0; j < 체크수; j++) 정리.허가서체크.작업.push(!!작업체크[j]);
    return 정리;
  }

  var 규칙 = { 빠진정보찾기: 빠진정보찾기, 결과다듬기: 결과다듬기, 분류찾기: 분류찾기, 근거다듬기: 근거다듬기, 사진점검다듬기: 사진점검다듬기 };
  if (typeof module !== "undefined" && module.exports) module.exports = 규칙;
  else 전역.규칙 = 규칙;
})(typeof window !== "undefined" ? window : globalThis);
