// 서류.js - 판단 결과(AI.js가 만들고 규칙.js가 다듬은 것)를 서류 4장의 {{표시}}에 들어갈 값으로 바꾼다.
// 값은 { 서류이름: { 표시이름: 글 } } 모양이다. 표시 이름은 양식/*.hwpx 안의 {{표시}}와 같아야 한다.
(function (전역) {
  "use strict";

  var 서류이름 = ["승인요청서", "TBM활동일지", "안전작업허가서", "위험성평가표"];
  var 위험성평가_행수 = 6; // 양식의 위험요인 줄 수 (만들기도구/양식만들기.py 와 같아야 함)
  var 체크 = function (참) { return 참 ? "■" : "□"; };
  var 해당없음 = "\uE001"; // 한글.js의 해당없음과 같은 글자 (일부러 비워 두는 칸)

  // 사람이 직접 써야 하는 칸 (도구가 비워 두는 것이 정상인 칸)
  var 직접쓰는칸 = {
    승인요청서: ["기타사항", "검토의견"],
    TBM활동일지: ["수량", "확인서명", "참석자"],
    안전작업허가서: ["승인번호", "비상연락망", "검토의견"],
    위험성평가표: ["예정일", "완료일", "담당자"],
  };

  function 줄바꿈목록(배열) { return 배열.map(function (x, i) { return (i + 1) + ". " + x; }).join("\n"); }

  // 결과: 판단 결과(결과다듬기를 거친 것), 입력: 2단계에서 사람이 고친 값
  function 값만들기(결과, 입력) {
    var 정보 = 결과.정보 || {};
    입력 = 입력 || {};
    var 가져오기 = function (키, 기본) {
      var 값 = 입력[키] != null && 입력[키] !== "" ? 입력[키] : 정보[키];
      return 값 == null || 값 === "" ? (기본 == null ? "" : 기본) : String(값);
    };
    var 날짜 = 가져오기("날짜"), 시간 = 가져오기("시간");
    var 일시 = (날짜 + (시간 ? " " + 시간 : "")).trim();
    var 작업명 = 가져오기("작업내용");
    var 장소 = 가져오기("장소"), 인원 = 가져오기("인원");
    var 구분 = 가져오기("구분", "자체작업");
    var 업체 = 구분 === "도급사업" ? 가져오기("업체명") : "";
    var 기구 = Array.isArray(입력.사용기구) ? 입력.사용기구 : (정보.사용기구 || []);
    var 서명 = 가져오기("작성자");

    var 위험 = 결과.위험요인 || [];
    var 경고 = (결과.경고 || []).slice();
    if (위험.length > 위험성평가_행수) 경고.push("위험요인이 " + 위험.length + "개라 양식의 " + 위험성평가_행수 + "줄을 넘어서 앞의 " + 위험성평가_행수 + "개만 넣었습니다.");

    var 값 = {};
    값.승인요청서 = {
      구분: 구분, 작업명: 작업명, 작업장소: 장소, 작업일시: 일시, 작업인원: 인원,
      승강기사용: 가져오기("승강기사용"), 감독자연락처: 가져오기("감독자연락처"),
      사전조사: (결과.승인요청서 || {}).사전조사 || "", 안전대책: (결과.승인요청서 || {}).안전대책 || "",
      기타사항: "", 검토의견: "",
    };
    값.TBM활동일지 = {
      현장명: 장소, 업체명: 구분 === "도급사업" ? 업체 : "자체", 일자: 날짜, 작업위치: 장소, 공종: "고소작업",
      작업명: 작업명, 투입장비: 기구.join(", "), 수량: "", 투입인원: 인원,
      위험요인: (결과.TBM || {}).위험요인 || "", 안전대책: (결과.TBM || {}).안전대책 || "",
      확인서명: "", 교육내용: (결과.TBM || {}).교육내용 || "", 참석자: "",
    };
    var 허가 = {
      작업명: 작업명, 작업일시: 일시, 작업인원: 인원, 업체명: 구분 === "도급사업" ? 업체 : "자체",
      작업장소: 장소, 작성자: 서명, 확인자: 가져오기("확인자"), 승인번호: "",
      비상연락망: "", 안전중점: 결과.안전중점 || "", 교육확인: "□ 작업 전 안전보건교육 실시 확인", 검토의견: "",
    };
    var 허가체크 = 결과.허가서체크 || { 공통: [], 고소: [] };
    for (var i = 0; i < 7; i++) 허가["공통" + (i + 1)] = 체크((허가체크.공통 || [])[i]);
    for (var j = 0; j < 8; j++) 허가["고소" + (j + 1)] = 체크((허가체크.고소 || [])[j]);
    값.안전작업허가서 = 허가;

    var 평가 = {};
    for (var n = 1; n <= 위험성평가_행수; n++) {
      var x = 위험[n - 1];
      var 접두 = "행" + n + "_";
      var 열 = ["공정", "세부작업", "분류", "상황", "조치", "빈도", "강도", "점수", "대책", "후빈도", "후강도", "후점수", "예정일", "완료일", "담당자"];
      열.forEach(function (k) { 평가[접두 + k] = 직접쓰는칸.위험성평가표.indexOf(k) >= 0 && x && x.점수 >= 8 ? "" : 해당없음; });
      if (!x) continue;
      평가[접두 + "공정"] = "고소작업";
      평가[접두 + "세부작업"] = 작업명;
      평가[접두 + "분류"] = x.분류;
      평가[접두 + "상황"] = x.상황결과;
      평가[접두 + "조치"] = x.현재조치;
      평가[접두 + "빈도"] = String(x.빈도);
      평가[접두 + "강도"] = String(x.강도);
      평가[접두 + "점수"] = String(x.점수);
      if (x.점수 >= 8) {
        평가[접두 + "대책"] = x.감소대책;
        평가[접두 + "후빈도"] = String(x.개선후빈도);
        평가[접두 + "후강도"] = String(x.개선후강도);
        평가[접두 + "후점수"] = String(x.개선후점수);
      }
    }
    값.위험성평가표 = 평가;
    값.경고 = 경고;
    return 값;
  }

  // 도구가 채우지 못한 칸 목록 (사람이 직접 쓰는 칸, 안 쓴 위험요인 줄, 8점 미만 줄의 개선 칸은 뺀다)
  function 빈칸목록(값, 결과) {
    var 목록 = [];
    var 위험 = (결과 && 결과.위험요인) || [];
    서류이름.forEach(function (이름) {
      var 서류값 = 값[이름] || {};
      Object.keys(서류값).forEach(function (키) {
        if (String(서류값[키]).trim() !== "") return;
        if ((직접쓰는칸[이름] || []).some(function (k) { return 키 === k || 키.slice(-k.length - 1) === "_" + k; })) return;
        var 행 = 키.match(/^행(\d+)_(.+)$/);
        if (행) {
          var x = 위험[parseInt(행[1], 10) - 1];
          if (!x) return;
          if (x.점수 < 8 && ["대책", "후빈도", "후강도", "후점수"].indexOf(행[2]) >= 0) return;
        }
        if (이름 === "승인요청서" && 키 === "구분") return;
        목록.push({ 서류: 이름, 키: 키 });
      });
    });
    return 목록;
  }

  var 서류 = { 서류이름: 서류이름, 값만들기: 값만들기, 빈칸목록: 빈칸목록, 줄바꿈목록: 줄바꿈목록 };
  if (typeof module !== "undefined" && module.exports) module.exports = 서류;
  else 전역.서류 = 서류;
})(typeof window !== "undefined" ? window : globalThis);
