# 연습용 가상 양식(.hwpx) 4개를 만드는 보조 프로그램입니다. (도구를 쓰는 사람은 실행할 필요 없음)
# 실행: python3 양식만들기.py   (python-hwpx 가 설치된 환경에서)
# 만들어진 양식에는 {{작업명}} 같은 표시가 들어 있고, 도구(한글.js)가 이 표시를 값으로 바꿉니다.
import csv
import os
from hwpx import HwpxDocument

여기 = os.path.dirname(os.path.abspath(__file__))
루트 = os.path.dirname(여기)
출력폴더 = os.path.join(루트, "양식")
os.makedirs(출력폴더, exist_ok=True)

MM = 283.46  # 1mm 의 한글 단위(HWPUNIT)


def 체크항목읽기():
    공통, 고소 = [], []
    with open(os.path.join(루트, "연습자료", "허가서체크항목.csv"), encoding="utf-8-sig") as f:
        for 줄 in csv.DictReader(f):
            (공통 if 줄["구분"] == "공통사항" else 고소).append(줄["항목"])
    return 공통, 고소


def 표만들기(문서, 제목, 줄들, 열수, 열너비mm, 가로=False):
    """줄들: 한 줄은 [(글자, 칸수), ...]. 칸수가 2 이상이면 가로로 합친다."""
    문서.add_paragraph(제목)
    문서.add_paragraph("")
    표 = 문서.add_table(len(줄들), 열수)
    표.set_column_widths([int(w * MM) for w in 열너비mm])
    for r, 줄 in enumerate(줄들):
        c = 0
        for 글자, 칸수 in 줄:
            표.set_cell_text(r, c, 글자)
            if 칸수 > 1:
                표.merge_cells(r, c, r, c + 칸수 - 1)
            c += 칸수
    return 표


def 저장(문서, 이름):
    경로 = os.path.join(출력폴더, 이름)
    문서.save_to_path(경로)
    print("만듦:", 경로)


def 한줄(제목, 키, 칸수=3):
    return [(제목, 1), ("{{" + 키 + "}}", 칸수)]


